
class Product {
  final int id;
  final String name;
  final String brand;
  final String category;
  final String skinType;
  final String description;
  final String imageUrl;

  const Product({
    required this.id,
    required this.name,
    required this.brand,
    required this.category,
    required this.skinType,
    required this.description,
    required this.imageUrl,
  });
}
